// Подключить stdio-сервер, просмотреть и одобрить тул, вызвать через Предохранитель,
// увидеть подмену схемы и выключить подключение. Без настоящих моделей и ключей.
const { chromium } = require("playwright");
const fs = require("fs");
const path = require("path");
const URL = process.env.BENDER_URL;
const OUT = process.argv[2];

async function main() {
  const stateFile = path.join(OUT, "fake-mcp-state.json");
  fs.writeFileSync(stateFile, JSON.stringify({capabilities:{tools:{},resources:{},prompts:{}},resources:[{uri:'notes:///проверка',name:'Проверочная заметка',description:'Данные — не указания'}],prompts:[{name:'план',arguments:[{name:'тема',required:true}]}]}));
  const browser = await chromium.launch();
  const errors = [];
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
    const page = await context.newPage();
    page.on("pageerror", e => errors.push(e.message));
    page.on("console", m => { if (m.type() === "error") errors.push(m.text()); });
    await page.goto(URL + "/#/mcp");
    // Старый транспорт настраивается тем же экраном и сам не подключается.
    await page.getByRole('button',{name:'Добавить сервер',exact:true}).click();
    await page.fill('[name="mcp-id"]','old');
    await page.selectOption('[name="mcp-transport"]','sse');
    await page.fill('[name="mcp-url"]',process.env.FAKE_URL+'/legacy-sse');
    await page.getByRole('button',{name:'Сохранить',exact:true}).click();
    const old=page.locator('[data-server="old"]');await old.waitFor();
    if(!(await old.innerText()).includes(process.env.FAKE_URL+'/legacy-sse'))throw Error('Адрес старого SSE не показан');
    const saved=await page.evaluate(async()=>await(await fetch('/api/mcp')).json());
    if(saved.servers[0].enabled||saved.servers[0].connected||saved.servers[0].transport!=='sse')throw Error('Старый SSE сам подключился');
    await old.getByRole('button',{name:'Изменить',exact:true}).click();
    if(await page.locator('[name="mcp-transport"]').inputValue()!=='sse')throw Error('Транспорт потерялся при изменении');
    await page.getByRole('button',{name:'Отмена',exact:true}).click();
    await old.getByRole('button',{name:'Удалить',exact:true}).click();await old.waitFor({state:'detached'});
    await page.getByRole("button", { name: "Добавить сервер", exact: true }).click();
    await page.fill('[name="mcp-id"]', "test");
    await page.fill('[name="mcp-name"]', "Проверочный сервер");
    await page.fill('[name="mcp-program"]', "python3");
    await page.fill('[name="mcp-args"]', path.resolve("tests/fixtures/fake_mcp.py") + "\n" + stateFile);
    await page.fill('[name="mcp-cwd"]', path.resolve(OUT));
    await page.getByRole("button", { name: "Сохранить", exact: true }).click();
    await page.getByRole("checkbox", { name: "Включить test" }).click();
    await page.waitForFunction(() => document.querySelector('[aria-label="Включить test"]').checked);
    await page.getByRole("button", { name: "Обнаружить тулы", exact: true }).click();
    await page.waitForSelector("text=нужно одобрение");
    await page.locator(".mcp-tool summary").click();
    await page.waitForSelector('pre:has-text("inputSchema")');
    await page.screenshot({ path: path.join(OUT, "mcp-review.png"), fullPage: true });
    await page.getByRole("button", { name: "Одобрить просмотренные определения", exact: true }).click();
    await page.waitForSelector("text=одобрено");
    await page.goto(URL + "/#/polygon");
    await page.selectOption("select.select", "mcp__test__echo");
    await page.fill("textarea.textarea.mono", JSON.stringify({ text: "Привет из MCP" }));
    await page.getByRole("button", { name: "Выполнить", exact: true }).click();
    await page.waitForSelector(".badge.amber:has-text('ждут ответа')");
    // Карточку хозяин открывает во второй вкладке, пока Полигон ждёт результата.
    const guard = await page.context().newPage();
    await guard.goto(URL + "/#/guard");
    await guard.waitForSelector(".approval:has-text('MCP test: echo')");
    await guard.getByRole("button", { name: "Разрешить один раз", exact: true }).click();
    await guard.locator(".approval").waitFor({ state: "detached" });
    await guard.close();
    await page.waitForSelector("text=Привет из MCP");
    await page.waitForSelector("text=НЕДОВЕРЕННОЕ");
    const state = JSON.parse(fs.readFileSync(stateFile));
    if (state.calls !== 1) throw Error("Вызов не исполнен ровно один раз");
    await page.goto(URL + '/#/mcp');
    await page.getByRole('checkbox',{name:'Ресурсы и шаблоны MCP',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('[aria-label="Ресурсы и шаблоны MCP"]').checked);
    await page.getByRole('button',{name:'Обнаружить ресурсы и шаблоны',exact:true}).click();
    await page.locator('.mcp-content').first().waitFor();
    await page.locator('.mcp-content summary').first().click();
    await page.screenshot({path:path.join(OUT,'mcp-content-review.png'),fullPage:true});
    await page.getByRole('button',{name:'Одобрить каталог ресурсов и шаблонов',exact:true}).click();
    await page.waitForFunction(()=>document.querySelectorAll('.mcp-content .badge.green').length===2);
    await page.goto(URL + '/#/polygon');
    await page.selectOption('select.select','mcp_content');
    await page.fill('textarea.textarea.mono',JSON.stringify({action:'read',server:'test',uri:'notes:///проверка'}));
    await page.getByRole('button',{name:'Выполнить',exact:true}).click();
    await page.waitForSelector(".badge.amber:has-text('ждут ответа')");
    const contentGuard=await page.context().newPage();await contentGuard.goto(URL+'/#/guard');
    await contentGuard.waitForSelector('.approval:has-text("resources/read")');
    await contentGuard.getByRole('button',{name:'Разрешить один раз',exact:true}).click();
    await contentGuard.locator('.approval').waitFor({state:'detached'});await contentGuard.close();
    await page.waitForSelector('text=Данные ресурса');
    const afterContent=JSON.parse(fs.readFileSync(stateFile));
    if(afterContent.content_calls!==1||afterContent.calls!==1)throw Error('Ресурс/тул выполнены неверное число раз');
    afterContent.resources[0].description='Описание ресурса изменено';
    fs.writeFileSync(stateFile,JSON.stringify(afterContent));
    await page.goto(URL+'/#/mcp');
    await page.getByRole('button',{name:'Обнаружить ресурсы и шаблоны',exact:true}).click();
    await page.locator('.mcp-content .badge.amber').waitFor();
    await page.locator('.mcp-content summary').first().click();
    await page.locator('.mcp-content').first().getByText('Ранее одобрено',{exact:true}).waitFor();
    fs.writeFileSync(stateFile, JSON.stringify({ ...afterContent, description: "Определение изменено" }));
    await page.goto(URL + "/#/mcp");
    await page.getByRole("button", { name: "Обнаружить тулы", exact: true }).click();
    await page.waitForSelector("text=нужно одобрение");
    await page.locator(".mcp-tool summary").click();
    await page.waitForSelector("text=Ранее одобрено");
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForTimeout(350); // дождаться перестройки и анимации боковой панели
    if (await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)) throw Error("Горизонтальная прокрутка на телефоне");
    if (await page.locator(".page").evaluate(e => e.scrollWidth > e.clientWidth)) throw Error("Страница MCP шире телефона");
    await page.locator(".mcp-server").screenshot({ path: path.join(OUT, "mcp-changed-phone.png") });
    await page.locator('.mcp-tool').evaluate(element=>element.open=false);
    await page.locator('.mcp-content').first().evaluate(element=>element.open=true);
    await page.locator('.mcp-content').first().scrollIntoViewIfNeeded();
    if(await page.locator('.mcp-server').evaluate(element=>element.scrollWidth>element.clientWidth))throw Error('Содержимое MCP шире карточки на телефоне');
    await page.screenshot({path:path.join(OUT,'mcp-content-phone.png')});
    // Встречная форма: два отдельных решения Предохранителя и явный ввод хозяина.
    await page.getByRole('checkbox',{name:'Встречные запросы MCP',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('[aria-label="Встречные запросы MCP"]').checked);
    await page.locator('.mcp-server').getByRole('button',{name:'Изменить',exact:true}).click();
    await page.locator('.mcp-client-options summary').click();
    await page.getByRole('checkbox',{name:'MCP elicitation',exact:true}).check();
    await page.getByRole('button',{name:'Сохранить',exact:true}).click();
    const withInput=JSON.parse(fs.readFileSync(stateFile));
    withInput.client_requests={form:{method:'elicitation/create',params:{mode:'form',message:'Уточни тему проверки',requestedSchema:{type:'object',properties:{тема:{type:'string',title:'Тема',minLength:2},число:{type:'integer',title:'Число',minimum:1,maximum:5}},required:['тема','число']}}}};
    fs.writeFileSync(stateFile,JSON.stringify(withInput));
    await page.getByRole('button',{name:'Обнаружить тулы',exact:true}).click();
    await page.getByRole('button',{name:'Одобрить просмотренные определения',exact:true}).click();
    await page.goto(URL+'/#/polygon');
    await page.selectOption('select.select','mcp__test__echo');
    await page.fill('textarea.textarea.mono',JSON.stringify({text:'Запрос с формой'}));
    await page.getByRole('button',{name:'Выполнить',exact:true}).click();
    const inputGuard=await page.context().newPage();await inputGuard.goto(URL+'/#/guard');
    await inputGuard.waitForSelector('.approval:has-text("MCP test: echo")');
    await inputGuard.getByRole('button',{name:'Разрешить один раз',exact:true}).click();
    await inputGuard.waitForSelector('.approval:has-text("elicitation/create")');
    await inputGuard.getByRole('button',{name:'Разрешить один раз',exact:true}).click();await inputGuard.close();
    const inputPage=await page.context().newPage();await inputPage.goto(URL+'/#/mcp');
    await inputPage.locator('.mcp-input').waitFor();
    await inputPage.fill('[aria-label="тема"]','Подтверждённая тема');await inputPage.fill('[aria-label="число"]','2');
    await inputPage.setViewportSize({width:390,height:844});
    if(await inputPage.locator('.scrim').isVisible())await inputPage.locator('.scrim').click({position:{x:380,y:20}});
    await inputPage.waitForSelector('.sidebar',{state:'hidden'});await inputPage.locator('.mcp-input').scrollIntoViewIfNeeded();
    fs.writeFileSync(path.join(OUT,'mcp-input-layout.json'),JSON.stringify(await inputPage.evaluate(()=>Object.fromEntries(['html','.main','.page','.page-inner','.mcp-input','.mcp-input .field','.mcp-input .input'].map(selector=>{const element=document.querySelector(selector),rect=element.getBoundingClientRect();return [selector,{width:rect.width,left:rect.left,scroll:element.scrollWidth,client:element.clientWidth}];}))),null,2));
    if(await inputPage.locator('.mcp-input').evaluate(element=>element.scrollWidth>element.clientWidth))throw Error('Форма MCP шире телефона');
    if(await inputPage.locator('.page').evaluate(element=>element.scrollWidth>element.clientWidth))throw Error('Страница формы MCP шире телефона');
    await inputPage.screenshot({path:path.join(OUT,'mcp-input-phone.png')});
    await inputPage.getByRole('button',{name:'Отправить серверу',exact:true}).click();
    await inputPage.locator('.mcp-input').waitFor({state:'detached'});await inputPage.close();
    await page.waitForSelector('text=Подтверждённая тема');
    const afterInput=JSON.parse(fs.readFileSync(stateFile));
    if(afterInput.calls!==2||afterInput.round_trips!==2||afterInput.client_responses.form.content.число!==2)throw Error('Форма MRTR не завершила ровно одно действие');
    await page.goto(URL+'/#/mcp');
    // Кому доступен: снять «всем», выдать одному агенту — одобрение тулов остаётся.
    const main = (await page.evaluate(async () => await (await fetch('/api/agents')).json())).agents.find(a => a.id === 'main');
    const server = page.locator('[data-server="test"]');
    await server.getByRole('checkbox', { name: 'Всем агентам test', exact: true }).click();
    await server.locator('.badge.amber:has-text("никому")').waitFor();
    await server.getByRole('checkbox', { name: `test для ${main.name}`, exact: true }).click();
    await server.locator('.badge.amber:has-text("никому")').waitFor({ state: 'detached' });
    const chosen = await page.evaluate(async () => await (await fetch('/api/mcp')).json());
    const picked = chosen.servers.find(s => s.id === 'test');
    if (JSON.stringify(picked.agents) !== '["main"]' || !picked.visible || !picked.tools[0].approved) throw Error('Выбор агентов MCP не сохранился или сбросил одобрение');
    await server.locator('.mcp-agents').screenshot({ path: path.join(OUT, 'mcp-agents.png') });
    await server.getByRole('checkbox', { name: 'Всем агентам test', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[aria-label="Всем агентам test"]').checked);
    await page.getByRole("checkbox", { name: "Включить test" }).click();
    await page.waitForFunction(() => !document.querySelector('[aria-label="Включить test"]').checked);
    if (errors.length) throw Error(errors.join("\n"));
    console.log("MCP: подключение, одобрение, Предохранитель, вызов и карантин изменений — OK");
  } finally {
    await browser.close();
  }
}
main().catch(e => { console.error(e); process.exit(1); });
