def _coerce(f: Field, value):
    t = f.type
    try:
        if t == "bool":
            if isinstance(value, str):
                v = value.strip().lower()
                if v in ("1", "true", "да", "yes", "on", "вкл"):
                    return True
                if v in ("0", "false", "нет", "no", "off", "выкл"):
                    return False
                raise ValueError
            return bool(value)
        if t == "int":
            value = int(value)
        elif t == "float":
            value = float(value)
            if value!=value or value in (float("inf"),float("-inf")):raise ValueError
        elif t in ("str", "choice"):
            value = str(value)
        elif t == "text":
            value = str(value).replace("\r\n", "\n").strip()
            if f.max is not None and len(value) > f.max:
                raise HumanError("bad_setting", f"«{f.title}»: слишком длинно", f"Не больше {f.max:g} знаков; сейчас {len(value)}. Сократи: текст попадает в каждый запрос к модели.")
            return value
        elif t == "json":
            # Пульт прежних версий присылал JSON текстом, и он оборачивался в кавычки при каждом
            # сохранении. Строку раскрываем до значения; не-JSON — понятная ошибка.
            for _ in range(8):
                if not isinstance(value, str):
                    break
                stripped = value.strip()
                if not stripped:
                    return value
                try:
                    value = json.loads(stripped)
                except ValueError:
                    if stripped[0] in '[{"':
                        raise HumanError("bad_setting", f"«{f.title}»: это не JSON", "Проверь скобки, запятые и двойные кавычки.") from None
                    break
            return value
    except (TypeError, ValueError, OverflowError):
        raise HumanError("bad_setting", f"Неподходящее значение для «{f.title}»", f"Ожидается {t}.") from None
    if t == "choice" and f.choices and value not in f.choices:
        raise HumanError("bad_setting", f"Нет такого варианта для «{f.title}»", "Варианты: " + ", ".join(f"{k} ({v})" for k, v in f.choices.items()))
    if f.min is not None and value < f.min:
        raise HumanError("bad_setting", f"«{f.title}»: слишком мало", f"Минимум {f.min:g}.")
    if f.max is not None and value > f.max:
        raise HumanError("bad_setting", f"«{f.title}»: слишком много", f"Максимум {f.max:g}.")
    return value


